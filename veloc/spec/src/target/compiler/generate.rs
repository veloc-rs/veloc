pub(crate) fn generate_enum(output: &mut String, final_inst_defs: &HashMap<String, FinalInstDef>) {
    let mut sorted_insts: Vec<_> = final_inst_defs.keys().cloned().collect();
    sorted_insts.sort();

    writeln!(
        output,
        r#"
/// 目标架构指令特化
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TargetInst {{"#
    )
    .unwrap();
    for name in &sorted_insts {
        writeln!(output, "    {},", name).unwrap();
    }
    writeln!(output, "}}").unwrap();
}

pub(crate) fn generate_enum_conversions(
    output: &mut String,
    final_inst_defs: &HashMap<String, FinalInstDef>,
) {
    let mut sorted_insts: Vec<_> = final_inst_defs.keys().cloned().collect();
    sorted_insts.sort();

    writeln!(
        output,
        r#"
impl TargetInst {{
    pub fn from_u32(op: u32) -> Self {{
        match op {{"#
    )
    .unwrap();
    for (i, name) in sorted_insts.iter().enumerate() {
        writeln!(output, "            {} => Self::{},", i + 1, name).unwrap();
    }
    writeln!(
        output,
        r#"            _ => panic!("Unknown opcode: {{}}", op),
        }}
    }}

    pub const fn as_u32(&self) -> u32 {{
        match self {{"#
    )
    .unwrap();
    for (i, name) in sorted_insts.iter().enumerate() {
        writeln!(output, "            Self::{} => {},", name, i + 1).unwrap();
    }
    writeln!(output, "        }}\n    }}\n}}").unwrap();
}

pub(crate) fn reg_const_name(name: &str) -> String {
    format!("REG_{}", sanitize_ident(name).to_ascii_uppercase())
}

pub(crate) fn format_slice(entries: Vec<String>) -> String {
    if entries.is_empty() {
        "&[]".to_string()
    } else {
        format!("&[{}]", entries.join(", "))
    }
}

fn format_reg_metadata_slice(
    regs: &[String],
    reg_names: &BTreeSet<String>,
    inst_name: &str,
    kind: &str,
) -> String {
    let entries = regs
        .iter()
        .map(|reg| {
            if !reg_names.contains(reg) {
                panic!(
                    "instruction {} references unknown {} register {}",
                    inst_name, kind, reg
                );
            }
            reg_const_name(reg)
        })
        .collect();
    format_slice(entries)
}

pub(super) fn generate_target_inst_metadata(
    output: &mut String,
    module: &crate::target::ast::Module,
    final_inst_defs: &HashMap<String, FinalInstDef>,
    cpu: &super::cpu::Plan,
) {
    let reg_names: BTreeSet<String> = module
        .defs
        .iter()
        .filter_map(|def| match def {
            Def::Reg(reg) => Some(reg.name.clone()),
            _ => None,
        })
        .collect();

    let mut sorted_insts: Vec<_> = final_inst_defs.keys().cloned().collect();
    sorted_insts.sort();

    writeln!(
        output,
        "\n/// Target instruction metadata generated from checked OpSpec instruction contracts."
    )
    .unwrap();
    for name in &sorted_insts {
        let inst_def = final_inst_defs
            .get(name)
            .unwrap_or_else(|| panic!("missing final inst def for {}", name));
        let const_name = format!(
            "TARGET_INST_{}_METADATA",
            sanitize_ident(name).to_ascii_uppercase()
        );
        let schedule = match &inst_def.schedule_class {
            Some(class) => format!(
                "crate::target::ScheduleClass::Modeled(crate::target::ScheduleClassId({}))",
                cpu.schedule_class(class),
            ),
            None => {
                assert!(inst_def.is_pseudo, "checked machine instruction cost");
                "crate::target::ScheduleClass::Pseudo".into()
            }
        };
        writeln!(
            output,
            "pub const {const_name}: TargetInstMetadata = TargetInstMetadata {{"
        )
        .unwrap();
        writeln!(output, "    schedule_class: {schedule},").unwrap();
        writeln!(output, "    movable: {},", inst_def.movable).unwrap();
        let memory = match &inst_def.memory {
            Some(memory) => {
                let address = memory.address.map_or("None".into(), |(base, offset)|
                    format!("Some(crate::target::TargetMemoryAddress {{ base: {base}, offset: {offset} }})"));
                format!(
                    "Some(crate::target::TargetMemoryAccess {{ effect: veloc_types::MemoryEffects::{}, bytes: {}, address: {address} }})",
                    memory.kind.to_uppercase(),
                    memory.bytes
                )
            }
            None => "None".into(),
        };
        writeln!(output, "    memory: {memory},").unwrap();
        let constraints = inst_def.operands.iter().filter_map(|op| match op {
            OperandConstraint::Def(n) => Some((n, true)),
            OperandConstraint::Use(n) => Some((n, false)),
            _ => None,
        });
        let mut defs = 0;
        let mut uses = 0;
        let mut entries = Vec::new();
        let mut state_operands = Vec::new();
        for (operand, result) in constraints {
            let index = if result {
                let n = defs;
                defs += 1;
                n
            } else {
                let n = uses;
                uses += 1;
                n
            };
            let registers = &inst_def
                .reg_classes
                .iter()
                .find(|(name, _)| name == operand)
                .expect("checked register constraint")
                .1;
            let placement = if let [register] = registers.as_slice() {
                format!("Placement::Fixed({})", reg_const_name(register))
            } else {
                format!(
                    "Placement::Registers({})",
                    format_slice(registers.iter().map(|r| reg_const_name(r)).collect())
                )
            };
            let domain = if result { "Result" } else { "Input" };
            if inst_def.state_operands.contains(operand) {
                let unit = reg_const_name(&registers[0]);
                state_operands.push(format!("veloc_lir::StateOperand {{ operand: OperandRef::{domain}({index}), unit: veloc_lir::PReg::new({unit}.0) }}"));
            }
            entries.push(format!("OperandConstraint {{ operand: OperandRef::{domain}({index}), placement: {placement} }}"));
        }
        for &(dst, src) in &inst_def.ties {
            let def = inst_def.operands[..dst]
                .iter()
                .filter(|op| matches!(op, OperandConstraint::Def(_)))
                .count();
            let input = inst_def.operands[..src]
                .iter()
                .filter(|op| matches!(op, OperandConstraint::Use(_)))
                .count();
            entries.push(format!("OperandConstraint {{ operand: OperandRef::Result({def}), placement: Placement::Reuse({input}) }}"));
        }
        writeln!(output, "    constraints: {},", format_slice(entries)).unwrap();
        writeln!(
            output,
            "    state_operands: {},",
            format_slice(state_operands)
        )
        .unwrap();
        writeln!(
            output,
            "    flow: veloc_lir::ControlFlow::{},",
            inst_def.flow
        )
        .unwrap();
        writeln!(
            output,
            "    clobbers: {},",
            format_reg_metadata_slice(&inst_def.clobbers, &reg_names, name, "clobber")
        )
        .unwrap();
        writeln!(output, "}};").unwrap();
    }

    writeln!(
        output,
        "\npub const fn target_inst_metadata(opcode: TargetInst) -> &'static TargetInstMetadata {{"
    )
    .unwrap();
    writeln!(output, "    match opcode {{").unwrap();
    for name in &sorted_insts {
        let const_name = format!(
            "TARGET_INST_{}_METADATA",
            sanitize_ident(name).to_ascii_uppercase()
        );
        writeln!(
            output,
            "        TargetInst::{name} => &{const_name},",
            name = name,
            const_name = const_name
        )
        .unwrap();
    }
    writeln!(output, "    }}").unwrap();
    writeln!(output, "}}").unwrap();
    output.push_str(r#"
impl TargetInst {
    /// Construct register operands and destruction effects from the schema.
    pub fn write(self, writer: veloc_lir::InstWriter<'_>, results: &[Reg], inputs: &[Reg], fields: veloc_lir::Fields) -> veloc_lir::InstId {
        let metadata = target_inst_metadata(self);
        for state in metadata.state_operands {
            assert_eq!(state.operand.get(inputs, results), Some(&Reg::from(state.unit)),
                "state operands must be physical before instruction construction");
        }
        writer.with_clobbers(metadata.clobbers.iter().copied())
            .write(veloc_lir::MachineOpcode::Target(self.as_u32()), results, inputs, fields)
    }
}
"#);
}

pub(crate) fn generate_validation(out: &mut String, instructions: &HashMap<String, FinalInstDef>) {
    out.push_str("impl TargetInst { pub const fn is_pseudo(self) -> bool { match self {\n");
    let mut ordered: Vec<_> = instructions.iter().collect();
    ordered.sort_by_key(|(name, _)| *name);
    for (name, inst) in ordered {
        writeln!(out, "Self::{name} => {},", inst.is_pseudo).unwrap();
    }
    out.push_str("} } }\n");
    out.push_str(
        "impl TargetInst { pub const fn required_features(self) -> FeatureSet { match self {\n",
    );
    let mut ordered: Vec<_> = instructions.iter().collect();
    ordered.sort_by_key(|(name, _)| *name);
    for (name, instruction) in ordered {
        if !instruction.requires.is_empty() {
            let set = instruction
                .requires
                .iter()
                .fold("FeatureSet::empty()".to_owned(), |set, feature| {
                    format!("{set}.with(Feature::{feature})")
                });
            writeln!(out, "Self::{name} => {set},").unwrap();
        }
    }
    out.push_str("_ => FeatureSet::empty(),\n} } }\n");
    out.push_str(r#"impl TargetInst {
    pub fn validate(&self, function: &veloc_lir::MachineFunction, inst: &veloc_lir::InstRef<'_>, mode: crate::target::ValidationMode, features: FeatureSet) -> crate::Result<()> {
        for feature in self.required_features().iter() {
            if !features.contains(feature) {
                return Err(crate::Error::codegen(alloc::format!(
                    "{self:?} requires target feature {}", feature.name()
                )));
            }
        }
        let invalid = || crate::Error::codegen(alloc::format!("invalid operands for {:?}", self));
        match self {
"#);
    let mut instructions: Vec<_> = instructions.iter().collect();
    instructions.sort_by_key(|(name, _)| *name);
    for (name, instruction) in instructions {
        let results = instruction
            .operands
            .iter()
            .filter(|op| matches!(op, OperandConstraint::Def(_)))
            .count();
        let inputs = instruction
            .operands
            .iter()
            .filter(|op| matches!(op, OperandConstraint::Use(_)))
            .count();
        let fields = instruction.operands.len() - inputs - results;
        // A call contract carries ABI register operands in addition to the
        // fixed, encoded operands declared by the machine opcode.
        let call = instruction
            .operands
            .iter()
            .any(|op| matches!(op, OperandConstraint::Attribute(_, AttributeKind::Call)));
        let boundary = call || instruction.flow == "Return";
        let count = if boundary { "<" } else { "!=" };
        let sequence = instruction
            .operands
            .iter()
            .any(|op| matches!(op, OperandConstraint::Attribute(_, AttributeKind::Blocks)));
        let mut checks = vec![format!(
            "inst.fields().len() {} {fields}",
            if sequence { "<" } else { "!=" }
        )];
        for (domain, length) in [("results", results), ("inputs", inputs)] {
            if !boundary || length != 0 {
                checks.push(format!("inst.{domain}().len() {count} {length}"));
            }
        }
        writeln!(
            out,
            "Self::{name} => {{\nif {} {{ return Err(invalid()); }}",
            checks.join(" || ")
        )
        .unwrap();
        if boundary {
            writeln!(out, "for &reg in inst.results()[{results}..].iter().chain(inst.inputs()[{inputs}..].iter()) {{ match mode {{ crate::target::ValidationMode::Allocated if !reg.is_preg() => return Err(invalid()), crate::target::ValidationMode::Virtual if reg.as_vreg().is_none_or(|v| function.vregs().get(v).is_none()) => return Err(invalid()), _ => {{}} }} }}").unwrap();
        }
        if boundary {
            for (domain, start) in [("Input", inputs), ("Result", results)] {
                let storage = if domain == "Input" {
                    "inputs"
                } else {
                    "results"
                };
                writeln!(out, "for index in {start}..inst.{storage}().len() {{ if !inst.constraints().iter().any(|c| c.operand == OperandRef::{domain}(index) && matches!(c.placement, Placement::Fixed(_))) {{ return Err(invalid()); }} }}").unwrap();
            }
        }
        if call {
            out.push_str("if inst.fields().call_info().is_none_or(|info| info.frame.is_none()) { return Err(invalid()); }\n");
        }
        for op in &instruction.operands {
            let OperandConstraint::Attribute(field_name, kind) = op else {
                continue;
            };
            if *kind == AttributeKind::Blocks {
                writeln!(out, "if inst.fields().successors().len() != inst.fields().len() {{ return Err(invalid()); }}").unwrap();
                continue;
            }
            let variant = kind.description().field_variant;
            let (index, _) = find_operand_info(field_name, &instruction.operands).unwrap();
            writeln!(out, "if !matches!(inst.fields().read({index}), veloc_lir::FieldValueRef::{variant}(_)) {{ return Err(invalid()); }}").unwrap();
        }
        for (name, set) in &instruction.value_types {
            let (index, op) = find_operand_info(name, &instruction.operands).unwrap();
            let storage = if matches!(op, OperandConstraint::Def(_)) {
                "results"
            } else {
                "inputs"
            };
            let accepts = crate::types::generate::accepts(set, "data.ty");
            writeln!(out, "if let Some(value) = inst.{storage}()[{index}].as_vreg() {{ let data = function.vregs().get(value).ok_or_else(invalid)?; if !({accepts}) {{ return Err(crate::Error::codegen(alloc::format!(\"invalid representation for {{:?}}.{name}: {{:?}}\", self, data.ty))); }} }}").unwrap();
        }
        for (name, registers) in &instruction.reg_classes {
            let (index, op) = find_operand_info(name, &instruction.operands).unwrap();
            let storage = if matches!(op, OperandConstraint::Def(_)) {
                "results"
            } else {
                "inputs"
            };
            let allowed = format_slice(registers.iter().map(|name| reg_const_name(name)).collect());
            writeln!(out, "let reg = inst.{storage}()[{index}];\nif reg.is_preg() {{ if !({allowed}).contains(&reg) {{ return Err(invalid()); }} }} else if mode == crate::target::ValidationMode::Allocated {{ return Err(invalid()); }}").unwrap();
        }
        for &(result, input) in &instruction.ties {
            let OperandConstraint::Def(ref result) = instruction.operands[result] else {
                unreachable!()
            };
            let input = match &instruction.operands[input] {
                OperandConstraint::Use(name) => name,
                _ => unreachable!(),
            };
            let (result, _) = find_operand_info(result, &instruction.operands).unwrap();
            let (input, _) = find_operand_info(input, &instruction.operands).unwrap();
            writeln!(out, "if mode == crate::target::ValidationMode::Allocated && inst.results()[{result}] != inst.inputs()[{input}] {{ return Err(invalid()); }}").unwrap();
        }
        out.push_str("Ok(())\n},\n");
    }
    out.push_str("} } }\n");
}

fn collect_canonical_regs<'a>(
    module: &'a crate::target::ast::Module,
) -> BTreeMap<u32, &'a crate::target::ast::RegDef> {
    let mut regs = BTreeMap::new();
    for def in &module.defs {
        if let Def::Reg(reg) = def {
            regs.entry(reg.id).or_insert(reg);
        }
    }
    regs
}

fn collect_reserved_reg_encs(module: &crate::target::ast::Module) -> BTreeSet<u32> {
    let mut regs = BTreeSet::new();
    for def in &module.defs {
        if let Def::Reg(reg) = def {
            if reg.reserved {
                regs.insert(reg.id);
            }
        }
    }
    regs
}

fn collect_special_role_regs<'a>(
    module: &'a crate::target::ast::Module,
) -> BTreeMap<String, &'a crate::target::ast::RegDef> {
    let mut roles = BTreeMap::new();
    let canonical_regs = collect_canonical_regs(module);
    for reg in canonical_regs.values() {
        for role in &reg.roles {
            roles.entry(role.clone()).or_insert(*reg);
        }
    }
    roles
}

pub(crate) fn generate_register_descriptors(
    output: &mut String,
    module: &crate::target::ast::Module,
) {
    let regs: Vec<_> = module
        .defs
        .iter()
        .filter_map(|def| match def {
            Def::Reg(reg) => Some(reg),
            _ => None,
        })
        .collect();
    let reg_classes: Vec<_> = module
        .defs
        .iter()
        .filter_map(|def| match def {
            Def::RegClass(class) => Some(class),
            _ => None,
        })
        .collect();

    if regs.is_empty() && reg_classes.is_empty() {
        return;
    }

    writeln!(
        output,
        "\n/// Register constants generated from OpSpec register constants."
    )
    .unwrap();
    for reg in &regs {
        let const_name = sanitize_ident(&format!("REG_{}", reg.name));
        writeln!(output, "pub const {}: Reg = Reg({});", const_name, reg.id).unwrap();
    }

    writeln!(output, "pub fn register_name(reg: Reg, bits: u32) -> Option<&'static str> {{ if !reg.is_preg() {{ return None; }} match (reg.index(), bits) {{").unwrap();
    for reg in &regs {
        // High-byte aliases need their own encoding selection and must not be
        // selected merely because the caller asks for an eight-bit view.
        if reg.alias.as_ref().is_some_and(|alias| alias.offset != 0) {
            continue;
        }
        writeln!(
            output,
            "({}, {}) => Some({:?}),",
            reg.id,
            reg.size,
            reg.name.to_ascii_lowercase()
        )
        .unwrap();
    }
    writeln!(output, "_ => None, }} }}").unwrap();

    writeln!(output, "pub fn register_encoding(reg: Reg) -> Option<u8> {{ if !reg.is_preg() {{ return None; }} match reg.index() {{").unwrap();
    let encodable_ids: BTreeSet<_> = reg_classes
        .iter()
        .flat_map(|class| &class.regs)
        .filter_map(|name| regs.iter().find(|reg| &reg.name == name).map(|reg| reg.id))
        .collect();
    for reg in regs
        .iter()
        .filter(|r| r.alias.is_none() && encodable_ids.contains(&r.id))
    {
        let encoding = u8::try_from(reg.hw_enc).expect("register hardware encoding fits a byte");
        writeln!(output, "{} => Some({encoding}),", reg.id).unwrap();
    }
    writeln!(output, "_ => None, }} }}").unwrap();
    let canonical_regs = collect_canonical_regs(module);
    let reg_encs = collect_reg_ids(module);
    writeln!(
        output,
        "pub const REGISTER_VIEWS: &[crate::target::RegisterView] = &["
    )
    .unwrap();
    for reg in &regs {
        if let Some(alias) = &reg.alias {
            let root = reg_const_name(&alias.base);
            writeln!(output, "crate::target::RegisterView {{ root: {root}, offset: {}, bits: {}, write: crate::target::RegisterWrite::{:?} }},", alias.offset, reg.size, alias.write).unwrap();
        }
    }
    writeln!(output, "];").unwrap();
    let reserved_encs = collect_reserved_reg_encs(module);
    let special_role_regs = collect_special_role_regs(module);
    writeln!(
        output,
        "\n/// Canonical physical register descriptors generated from OpSpec register constants."
    )
    .unwrap();
    writeln!(output, "pub const PHYS_REG_INFOS: &[RegInfo] = &[").unwrap();
    for reg in canonical_regs.values() {
        let const_name = sanitize_ident(&format!("REG_{}", reg.name));
        writeln!(
            output,
            "    RegInfo {{ preg: {const_name}, name: \"{name}\", size: {size}, hw_encoding: {enc} }},",
            const_name = const_name,
            name = reg.name.to_ascii_lowercase(),
            size = reg.size,
            enc = reg.hw_enc,
        )
        .unwrap();
    }
    writeln!(output, "];").unwrap();

    writeln!(
        output,
        "\n/// Reserved physical registers generated from OpSpec register constants."
    )
    .unwrap();
    let reserved_regs = canonical_regs
        .values()
        .filter(|reg| reserved_encs.contains(&reg.id))
        .map(|reg| sanitize_ident(&format!("REG_{}", reg.name)))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(
        output,
        "pub const RESERVED_REGS: &[Reg] = &[{}];",
        reserved_regs
    )
    .unwrap();

    if !special_role_regs.is_empty() {
        writeln!(
            output,
            "\n/// Special-register roles generated from OpSpec register constants."
        )
        .unwrap();
        for (role, reg) in special_role_regs {
            let const_name = sanitize_ident(&format!("SPECIAL_REG_{}", role)).to_ascii_uppercase();
            let reg_name = sanitize_ident(&format!("REG_{}", reg.name));
            writeln!(output, "pub const {}: Reg = {};", const_name, reg_name).unwrap();
        }
    }

    if reg_classes.is_empty() {
        return;
    }

    writeln!(
        output,
        "\n/// Register-class member slices generated from OpSpec RegisterClass constants."
    )
    .unwrap();
    for class in reg_classes {
        let const_name = sanitize_ident(&format!("REGCLASS_{}", class.name));
        let regs = class
            .regs
            .iter()
            .map(|reg| sanitize_ident(&format!("REG_{}", reg)))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(output, "pub const {}: &[Reg] = &[{}];", const_name, regs).unwrap();

        let allocatable_name = format!("{}_ALLOCATABLE", const_name);
        let allocatable = class
            .regs
            .iter()
            .filter_map(|reg_name| {
                let reg_enc = reg_encs.get(reg_name).copied()?;
                (!reserved_encs.contains(&reg_enc))
                    .then(|| sanitize_ident(&format!("REG_{}", reg_name)))
            })
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            output,
            "pub const {}: &[Reg] = &[{}];",
            allocatable_name, allocatable
        )
        .unwrap();
    }
}

pub(crate) fn check_abi_descriptors(
    module: &crate::target::ast::Module,
    types: &crate::types::Types,
    layouts: &super::layout::Plan,
) -> Result<(), String> {
    let registers = collect_reg_ids(module);
    let mut names = std::collections::BTreeSet::new();
    for def in &module.defs {
        let Def::Abi(abi) = def else {
            continue;
        };
        if !names.insert(&abi.name) {
            return Err(format!("duplicate ABI {}", abi.name));
        }
        abi_arch_expr(&abi.arch)?;
        let layout = layouts.get(&abi.layout)?;
        for rule in abi
            .args
            .iter()
            .chain(abi.variadic.iter().flatten())
            .chain(&abi.returns)
        {
            if rule.types.is_empty() {
                return Err(format!("ABI {} has an empty type domain", abi.name));
            }
            for source in &rule.types {
                let transport = rule.transport.as_ref().unwrap_or(source);
                let error = |reason: String| {
                    format!("ABI {} ({source} -> {transport}): {reason}", abi.name)
                };
                layout.slot(types, source).map_err(&error)?;
                let (size, align) = layout.slot(types, transport).map_err(&error)?;
                if source != transport {
                    let a = layout.bitcast_width(types, source).map_err(&error)?;
                    let b = layout.bitcast_width(types, transport).map_err(&error)?;
                    if a != b {
                        return Err(error(format!("bitcast widths differ ({a} and {b})")));
                    }
                }
                if let crate::target::ast::AbiActionDef::Stack {
                    size: slot_size,
                    align: slot_align,
                } = &rule.action
                {
                    if *slot_size < size || *slot_align < align {
                        return Err(error(format!(
                            "stack slot ({slot_size} bytes, alignment {slot_align}) cannot hold storage ({size} bytes, alignment {align})"
                        )));
                    }
                }
            }
            match &rule.action {
                crate::target::ast::AbiActionDef::Reg { regs, shadows } => {
                    if regs.is_empty() || (!shadows.is_empty() && shadows.len() != regs.len()) {
                        return Err(format!(
                            "ABI {} has invalid register/shadow lists",
                            abi.name
                        ));
                    }
                }
                crate::target::ast::AbiActionDef::Stack { size, align } => {
                    if *size == 0 || !align.is_power_of_two() {
                        return Err(format!("ABI {} has invalid stack allocation", abi.name));
                    }
                }
            }
        }
        for reg in abi
            .args
            .iter()
            .chain(abi.variadic.iter().flatten())
            .chain(&abi.returns)
            .flat_map(|rule| match &rule.action {
                crate::target::ast::AbiActionDef::Reg { regs, shadows } => {
                    regs.iter().chain(shadows).collect::<Vec<_>>()
                }
                crate::target::ast::AbiActionDef::Stack { .. } => Vec::new(),
            })
            .chain(abi.preserved.iter())
        {
            if !registers.contains_key(reg) {
                return Err(format!(
                    "ABI {} references unknown register {reg}",
                    abi.name
                ));
            }
        }
        for name in &abi.preserved {
            if module
                .defs
                .iter()
                .any(|def| matches!(def, Def::Reg(reg) if reg.name == *name && reg.alias.is_some()))
            {
                return Err(format!(
                    "ABI {} preserved registers must name storage roots: {name}",
                    abi.name
                ));
            }
        }
        if abi.stack.align.is_some_and(|a| !a.is_power_of_two()) {
            return Err(format!("ABI {} has invalid stack size/alignment", abi.name));
        }
    }
    Ok(())
}

pub(crate) fn generate_abi_descriptors(output: &mut String, module: &crate::target::ast::Module) {
    let reg_map = collect_reg_ids(module);
    let abis: Vec<_> = module
        .defs
        .iter()
        .filter_map(|def| match def {
            Def::Abi(abi) => Some(abi),
            _ => None,
        })
        .collect();

    if abis.is_empty() {
        return;
    }

    writeln!(
        output,
        "\n/// ABI allocation functions and descriptors generated from Spec."
    )
    .unwrap();

    for abi in abis {
        let prefix = sanitize_ident(&format!("ABI_{}", abi.name)).to_ascii_uppercase();
        let args_name = format!("{}_ARGS", prefix);
        let returns_name = format!("{}_RETURNS", prefix);
        let preserved_name = format!("{}_PRESERVED", prefix);

        generate_abi_assignment(output, &args_name, &abi.args, &reg_map);
        let variadic = if let Some(rules) = &abi.variadic {
            let name = format!("{prefix}_VARIADIC");
            generate_abi_assignment(output, &name, rules, &reg_map);
            format!("Some({name})")
        } else {
            "None".into()
        };
        generate_abi_assignment(output, &returns_name, &abi.returns, &reg_map);
        generate_abi_preserved_array(output, &preserved_name, &abi.preserved, &reg_map);

        let preserved: BTreeSet<_> = abi.preserved.iter().map(|name| reg_map[name]).collect();
        let mut words = Vec::<u64>::new();
        for def in &module.defs {
            let Def::Reg(reg) = def else { continue };
            if reg.alias.is_some()
                || preserved.contains(&reg.id)
                || reg
                    .roles
                    .iter()
                    .any(|role| role == "stack-pointer" || role == "frame-pointer")
            {
                continue;
            }
            let index = reg.id as usize;
            words.resize(words.len().max(index / 64 + 1), 0);
            words[index / 64] |= 1 << (index % 64);
        }
        writeln!(output, "static {prefix}_CLOBBERS: &[u64] = &{words:?};").unwrap();
        let arch = abi_arch_expr(&abi.arch).expect("checked ABI architecture");
        let layout = super::layout::symbol(&abi.layout);
        let align = abi.stack.align.unwrap_or(16);
        let reserved = abi.stack.reserved;

        writeln!(
            output,
            r#"
pub static {prefix}: AbiDescriptor = AbiDescriptor {{
    name: "{name}",
    arch: {arch},
    layout: &{layout},
    stack: StackArea {{
        align: {align},
        size: {reserved},
    }},
    args: {args_name},
    variadic: {variadic},
    returns: {returns_name},
    preserved: {preserved_name},
    clobbers: veloc_lir::RegMask::from_static({prefix}_CLOBBERS),
}};
"#,
            prefix = prefix,
            name = abi.name,
            arch = arch,
            align = align,
            reserved = reserved,
            args_name = args_name,
            returns_name = returns_name,
            preserved_name = preserved_name,
        )
        .unwrap();
    }
}

fn generate_abi_assignment(
    output: &mut String,
    name: &str,
    rules: &[crate::target::ast::AbiRuleDef],
    reg_map: &HashMap<String, u32>,
) {
    writeln!(output, "#[allow(non_snake_case)]\nfn {name}(ty: veloc_mir::Type, state: &mut AbiState) -> Result<AbiAssignment, crate::error::Error> {{").unwrap();
    for rule in rules {
        let transport = rule.transport.as_deref().unwrap_or("ty");
        writeln!(output, "    if matches!(ty, {}) {{", rule.types.join(" | ")).unwrap();
        match &rule.action {
            crate::target::ast::AbiActionDef::Reg { regs, shadows } => {
                let render = |regs: &[String]| {
                    regs.iter()
                        .map(|reg| reg_expr(reg_map.get(reg).copied()))
                        .collect::<Vec<_>>()
                        .join(", ")
                };
                writeln!(
                    output,
                    "        if let Some(loc) = state.assign(&[{}], &[{}]) {{ return Ok(AbiAssignment {{ ty: {transport}, loc }}); }}",
                    render(regs),
                    render(shadows)
                )
                .unwrap();
            }
            crate::target::ast::AbiActionDef::Stack { size, align } => {
                writeln!(output, "        return Ok(AbiAssignment {{ ty: {transport}, loc: state.stack({size}, {align})? }});").unwrap();
            }
        }
        writeln!(output, "    }}").unwrap();
    }
    writeln!(output, "    Err(crate::error::Error::codegen(alloc::format!(\"ABI has no available location for {{ty:?}}\")))\n}}").unwrap();
}

fn generate_abi_preserved_array(
    output: &mut String,
    const_name: &str,
    preserved: &[String],
    reg_map: &HashMap<String, u32>,
) {
    let regs: BTreeSet<_> = preserved.iter().map(|reg| reg_map[reg]).collect();
    let regs = regs
        .into_iter()
        .map(|id| reg_expr(Some(id)))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(output, "pub const {const_name}: &[Reg] = &[{regs}];").unwrap();
}

fn abi_arch_expr(arch: &str) -> Result<&'static str, String> {
    match arch {
        "X86_64" => Ok("TargetArch::X86_64"),
        "AArch64" => Ok("TargetArch::AArch64"),
        "Riscv64" => Ok("TargetArch::Riscv64"),
        "Wasm32" => Ok("TargetArch::Wasm32"),
        "Wasm64" => Ok("TargetArch::Wasm64"),
        _ => Err(format!("unsupported ABI architecture `{}`", arch)),
    }
}

fn reg_expr(enc: Option<u32>) -> String {
    match enc {
        Some(enc) => format!("Reg({})", enc),
        None => "Reg(0)".to_string(),
    }
}

pub(crate) fn sanitize_ident(name: &str) -> String {
    name.chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || ch == '_' {
                ch
            } else {
                '_'
            }
        })
        .collect()
}
