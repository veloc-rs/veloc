//! Typed expression rewrites. This backend emits patterns, not an e-graph or
//! storage-specific matcher. Parsing, imports and templates use the shared AST.
use crate::{
    Definitions, Error,
    syntax::{DeclKind, Kind, Node, Results},
};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

pub(crate) fn generate(
    source: &crate::Source,
    defs: &Definitions,
    dialect: &str,
    opcode: &str,
    types: &str,
) -> Result<String, Error> {
    if !super::identifier(dialect)
        || ![opcode, types]
            .iter()
            .all(|p| p.split("::").all(super::identifier))
    {
        return Err(Error::at(
            source.text(),
            0,
            "invalid equivalence Rust binding",
        ));
    }
    let aliases = source
        .declarations()
        .iter()
        .filter_map(|d| {
            if let DeclKind::TypeSet(n) = &d.kind {
                Some((d.name.clone(), n.clone()))
            } else {
                None
            }
        })
        .collect();
    let operations: BTreeMap<_, _> = defs.operations().map(|op| (op.name.clone(), op)).collect();
    let mut output =
        String::from("// @generated by veloc-spec. Type checking is not an equivalence proof.\n");
    let mut groups: BTreeMap<String, Vec<CheckedRule>> = BTreeMap::new();
    let mut program = Bytecode::new();
    // Primitive laws and authored rules share checking, query planning and
    // execution. Insert cheap primitive laws first within each opcode group.
    for op in &defs.ops {
        let Some(sem) = &op.semantics else { continue };
        if sem.primitive().is_none()
            || (op.identity.is_none()
                && op.absorbing.is_none()
                && !op.traits.contains("IDEMPOTENT"))
        {
            continue;
        }
        let mut domains = BTreeMap::<_, Vec<String>>::new();
        for instance in &sem.instances {
            let [a, b, result] = instance.kinds.as_slice() else {
                continue;
            };
            if !instance.scalar || instance.error.is_some() || a != b || a != result {
                continue;
            }
            let bits = match a {
                crate::types::Primitive::Int(bits) if *bits <= 64 => *bits,
                crate::types::Primitive::Bool => 1,
                _ => continue,
            };
            let constant = |value: veloc_semantics::BvConst| {
                // Pattern constants are masked to the matched type's width.
                // Share the all-ones rule across widths as with an authored -1.
                if value == veloc_semantics::BvConst::AllOnes {
                    u64::MAX
                } else {
                    value.eval(bits as u16).expect("validated semantic width") as u64
                }
            };
            let scalar = defs.types.scalars.iter().find(|s| s.ty == *a).unwrap();
            let domain = domains
                .entry((op.identity.map(constant), op.absorbing.map(constant)))
                .or_default();
            let ty = format!("Type::{}", scalar.exact());
            if !domain.contains(&ty) {
                domain.push(ty);
            }
        }
        for ((identity, absorbing), domain) in domains {
            let parameters = BTreeMap::from([("x".into(), 0)]);
            let mut checker = Checker {
                source: source.text(),
                dialect,
                domain: &domain,
                defs,
                operations: &operations,
                parameters: &parameters,
                bound: BTreeSet::new(),
            };
            let node = |kind| Node { offset: 0, kind };
            let x = node(Kind::Name("x".into()));
            let mut laws = Vec::new();
            if let Some(value) = identity {
                laws.push(("identity", node(Kind::Integer(value.into())), x.clone()));
            }
            if let Some(value) = absorbing {
                let value = node(Kind::Integer(value.into()));
                laws.push(("absorbing", value.clone(), value));
            }
            if op.traits.contains("IDEMPOTENT") {
                laws.push(("idempotent", x.clone(), x.clone()));
            }
            for (law, rhs_arg, rhs) in laws {
                let lhs = node(Kind::Call(
                    format!("{dialect}::{}", op.name),
                    vec![x.clone(), rhs_arg],
                ));
                let rule = checker.rule(&lhs, &rhs, None, types, &format!("{} {law}", op.name))?;
                groups.entry(op.name.clone()).or_default().push(rule);
            }
        }
    }
    for decl in source.declarations() {
        let DeclKind::Rule(sig) = &decl.kind else {
            continue;
        };
        let fail = |message| Error::at(source.text(), decl.offset, message);
        let [generic] = sig.generics.as_slice() else {
            return Err(fail(
                "equivalence rules require one explicit type parameter",
            ));
        };
        if generic.moves || !matches!(&sig.results, Results::Fixed(r) if r.is_empty()) {
            return Err(fail(
                "equivalence rules do not move types or declare return values",
            ));
        }
        let domain =
            super::typed::domain(source.text(), &generic.ty, &aliases, &mut BTreeSet::new())?;
        if domain.is_empty() {
            return Err(fail("empty equivalence type domain"));
        }
        let mut parameters = BTreeMap::new();
        for (i, p) in sig.params.iter().enumerate() {
            if p.moves
                || !matches!(&p.ty.kind, Kind::Name(n) if n == &generic.name)
                || parameters.insert(p.name.clone(), i).is_some()
            {
                return Err(fail(
                    "equivalence parameters must have the declared common type and unique names",
                ));
            }
        }
        for field in decl.fields.keys() {
            if !matches!(field.as_str(), "match" | "emit" | "when") {
                return Err(fail("unknown equivalence rule field"));
            }
        }
        let field = |key: &str| {
            decl.fields
                .get(key)
                .ok_or_else(|| fail("equivalence requires a source and replacement"))
        };
        let mut checker = Checker {
            source: source.text(),
            dialect,
            domain: &domain,
            defs,
            operations: &operations,
            parameters: &parameters,
            bound: BTreeSet::new(),
        };
        let rule = checker.rule(
            field("match")?,
            field("emit")?,
            decl.fields.get("when"),
            types,
            &format!("rule at byte {}", decl.offset),
        )?;
        let Kind::Call(root, _) = &field("match")?.kind else {
            unreachable!("checked operation pattern")
        };
        let root = root.strip_prefix(&format!("{dialect}::")).unwrap();
        groups.entry(root.to_owned()).or_default().push(rule);
    }
    writeln!(
        output,
        "fn group(opcode: {opcode}) -> Option<Group> {{\nmatch opcode {{"
    )
    .unwrap();
    let mut dependencies = BTreeSet::new();
    for (root, rules) in groups {
        for rule in &rules {
            rule.lhs
                .dependencies(&root, &mut Vec::new(), &mut dependencies);
        }
        let group = program.group(&rules);
        writeln!(output, "{opcode}::{root} => Some(Group {{ {group} }}),").unwrap();
    }
    writeln!(output, "_ => None,\n}}\n}}").unwrap();
    writeln!(output, "static DEPENDENCIES: &[Dependency] = &[").unwrap();
    for (root, path) in dependencies {
        let path = path
            .iter()
            .map(|op| format!("{opcode}::{op}"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            output,
            "Dependency {{ root: {opcode}::{root}, path: &[{path}] }},"
        )
        .unwrap();
    }
    writeln!(output, "];").unwrap();
    output.push_str(&program.emit(opcode));
    Ok(output)
}

struct CheckedRule {
    lhs: Expr,
    rhs: Expr,
    guard: Option<(usize, u64, bool)>,
    types: String,
    parameters: usize,
    name: String,
}

struct Checker<'a> {
    source: &'a str,
    dialect: &'a str,
    domain: &'a [String],
    defs: &'a Definitions,
    operations: &'a BTreeMap<String, crate::schema::Operation>,
    parameters: &'a BTreeMap<String, usize>,
    bound: BTreeSet<String>,
}
impl Checker<'_> {
    fn rule(
        &mut self,
        lhs: &Node,
        rhs: &Node,
        guard: Option<&Node>,
        types: &str,
        name: &str,
    ) -> Result<CheckedRule, Error> {
        self.bound.clear();
        let lhs_expr = self.pattern(lhs, true)?;
        if !matches!(&lhs.kind, Kind::Call(..)) {
            return Err(Error::at(
                self.source,
                lhs.offset,
                "equivalence match must be an operation",
            ));
        }
        let rhs_expr = self.pattern(rhs, false)?;
        let guard = guard.map(|node| self.guard(node)).transpose()?;
        let accepted = self
            .domain
            .iter()
            .map(|name| {
                let fail = |message| Error::at(self.source, lhs.offset, message);
                let exact = name
                    .strip_prefix("Type::")
                    .ok_or_else(|| fail("expected an exact Type constant"))?;
                if self.defs.type_domain(name).is_none() {
                    return Err(fail("unknown rule type"));
                }
                Ok(format!("{types}::{exact}"))
            })
            .collect::<Result<Vec<_>, Error>>()?
            .join(", ");
        Ok(CheckedRule {
            lhs: lhs_expr,
            rhs: rhs_expr,
            guard,
            types: accepted,
            parameters: self.parameters.len(),
            name: name.to_owned(),
        })
    }

    fn pattern(&mut self, node: &Node, bind: bool) -> Result<Expr, Error> {
        let fail = |message| Error::at(self.source, node.offset, message);
        match &node.kind {
            Kind::Name(name) => {
                let index = self
                    .parameters
                    .get(name)
                    .ok_or_else(|| fail("undeclared pattern variable"))?;
                if bind {
                    self.bound.insert(name.clone());
                } else if !self.bound.contains(name) {
                    return Err(fail("replacement uses an unmatched variable"));
                }
                Ok(Expr::Variable(*index))
            }
            Kind::Number(n) => Ok(Expr::Constant(u64::from(*n))),
            Kind::Integer(n) => {
                let bits = u64::try_from(*n)
                    .or_else(|_| i64::try_from(*n).map(|n| n as u64))
                    .map_err(|_| fail("literal exceeds 64 bits"))?;
                Ok(Expr::Constant(bits))
            }
            Kind::Unary("-", n) if matches!(n.kind, Kind::Number(_)) => {
                let Kind::Number(n) = n.kind else {
                    unreachable!()
                };
                Ok(Expr::Constant((-(n as i64)) as u64))
            }
            Kind::Call(path, args) => {
                let name = path
                    .strip_prefix(&format!("{}::", self.dialect))
                    .ok_or_else(|| fail("unknown equivalence dialect"))?;
                let op = self
                    .operations
                    .get(name)
                    .ok_or_else(|| fail("unknown equivalence operation"))?;
                let sig = op.signature.as_ref().map_err(|e| fail(e.as_str()))?;
                if op.constrained || sig.results.len() != 1 || sig.inputs.len() != args.len() {
                    return Err(fail(
                        "rule operation needs a fixed, unconstrained single-result signature",
                    ));
                }
                let model = self.defs.ops.iter().find(|op| op.name == name).unwrap();
                if model.traits.contains("MAY_TRAP") || model.semantics.is_none() {
                    return Err(fail(
                        "equivalence operation needs non-trapping declared semantics",
                    ));
                }
                for ty in self.domain {
                    let set = self
                        .defs
                        .type_domain(ty)
                        .ok_or_else(|| fail("unknown equivalence type"))?;
                    if !sig
                        .inputs
                        .iter()
                        .chain(&sig.results)
                        .all(|term| set.subset_of(&term.domain))
                    {
                        return Err(fail("operation does not accept every rule type"));
                    }
                }
                let children = args
                    .iter()
                    .map(|n| self.pattern(n, bind))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(Expr::Apply(name.to_owned(), children))
            }
            _ => Err(fail(
                "expected a value, integer literal or qualified operation call",
            )),
        }
    }
    fn guard(&self, node: &Node) -> Result<(usize, u64, bool), Error> {
        let fail = || {
            Error::at(
                self.source,
                node.offset,
                "guard requires matched_value == integer or matched_value != integer",
            )
        };
        let Kind::Binary(op @ ("==" | "!="), left, right) = &node.kind else {
            return Err(fail());
        };
        let Kind::Name(name) = &left.kind else {
            return Err(fail());
        };
        if !self.bound.contains(name) {
            return Err(fail());
        }
        let Kind::Number(value) = right.kind else {
            return Err(fail());
        };
        Ok((self.parameters[name], u64::from(value), *op == "=="))
    }
}

// Only the build-time compiler keeps recursive expressions. Runtime programs
// contain flat instructions with resolved register and backtracking locations.
enum Expr {
    Variable(usize),
    Constant(u64),
    Apply(String, Vec<Expr>),
}

/// Build-time byte assembler. Opcode numbers belong to the runtime enum;
/// operands and branch destinations are little-endian u32 values.
#[derive(Default)]
struct Code {
    bytes: Vec<String>,
    formats: BTreeMap<String, usize>,
}
impl Code {
    fn emit(&mut self, op: &str, args: &[usize]) {
        if let Some(arity) = self.formats.insert(op.to_owned(), args.len()) {
            assert_eq!(arity, args.len(), "inconsistent bytecode operands");
        }
        self.bytes.push(format!(
            "\n        // @{:04x} {op}\n        {op} as u8",
            self.bytes.len()
        ));
        for &arg in args {
            self.word(arg);
        }
    }
    fn word(&mut self, value: usize) {
        self.bytes
            .extend(veloc_bytecode::encode_u32(value).map(|b| b.to_string()));
    }

    fn patch(&mut self, offset: usize, value: usize) {
        for (dst, byte) in self.bytes[offset..offset + 4]
            .iter_mut()
            .zip(veloc_bytecode::encode_u32(value))
        {
            *dst = byte.to_string();
        }
    }
}

struct Bytecode {
    code: Code,
    opcodes: Vec<String>,
    constants: Vec<u64>,
    captures: Vec<usize>,
    types: Vec<String>,
    names: Vec<String>,
    bound: BTreeSet<usize>,
    slots: usize,
    cursors: usize,
    retry: usize,
}

impl Bytecode {
    fn new() -> Self {
        Self {
            code: Code::default(),
            opcodes: Vec::new(),
            constants: Vec::new(),
            captures: Vec::new(),
            types: Vec::new(),
            names: Vec::new(),
            bound: BTreeSet::new(),
            slots: 0,
            cursors: 0,
            retry: 0,
        }
    }

    fn group(&mut self, rules: &[CheckedRule]) -> String {
        let entry = self.code.bytes.len();
        let (mut slots, mut cursors) = (0, 0);
        let mut previous = None;
        let mut exit = None;
        for rule in rules {
            let ty = crate::bytecode::intern(&mut self.types, rule.types.clone());
            if previous != Some(ty) {
                if let Some(offset) = exit {
                    self.code.patch(offset, self.code.bytes.len());
                }
                self.code.emit("Op::CheckType", &[ty, 0]);
                exit = Some(self.code.bytes.len() - 4);
                previous = Some(ty);
            }
            let name = crate::bytecode::intern(&mut self.names, rule.name.clone());
            self.code.emit("Op::Begin", &[name, self.captures.len(), 0]);
            let capture_count = self.code.bytes.len() - 4;
            let start = self.captures.len();
            let size = self.compile(&rule.lhs, &rule.rhs, rule.guard, rule.parameters);
            self.code.patch(capture_count, self.captures.len() - start);
            slots = slots.max(size);
            cursors = cursors.max(self.cursors);
        }
        if let Some(offset) = exit {
            self.code.patch(offset, self.code.bytes.len());
        }
        self.code.emit("Op::Return", &[]);
        format!("entry: {entry}, slots: {slots}, cursors: {cursors}")
    }

    fn compile(
        &mut self,
        lhs: &Expr,
        rhs: &Expr,
        guard: Option<(usize, u64, bool)>,
        parameters: usize,
    ) -> usize {
        self.bound.clear();
        self.slots = parameters + 1;
        self.cursors = 0;
        self.retry = 0;
        let query_exit = self.scan(lhs, 0);
        if let Some((variable, value, equal)) = guard {
            let constant = self.constant(value);
            self.code.emit(
                "Op::CheckConstant",
                &[variable + 1, constant, usize::from(equal), self.retry],
            );
        }
        self.code.emit("Op::Capture", &[]);
        self.code.emit("Op::Jump", &[self.retry]);

        fn capture(expr: &Expr, variables: &mut BTreeSet<usize>) {
            match expr {
                Expr::Variable(v) => {
                    variables.insert(*v);
                }
                Expr::Apply(_, args) => {
                    for arg in args {
                        capture(arg, variables);
                    }
                }
                Expr::Constant(_) => {}
            }
        }
        let mut captures = BTreeSet::new();
        capture(rhs, &mut captures);
        let captures: Vec<_> = captures.into_iter().collect();
        let next_match = self.code.bytes.len();
        self.code.patch(query_exit, next_match);
        self.code.emit("Op::NextMatch", &[0]);
        let match_exit = self.code.bytes.len() - 4;
        let mut values = captures.len();
        if let Expr::Constant(value) = rhs {
            let constant = self.constant(*value);
            self.code.emit("Op::SetConstant", &[constant]);
        } else {
            let value = self.build(rhs, &captures, &mut values);
            self.code.emit("Op::Union", &[value]);
        }
        self.code.emit("Op::Jump", &[next_match]);
        self.code.patch(match_exit, self.code.bytes.len());
        self.captures.extend(captures.iter().map(|v| v + 1));
        self.slots.max(values)
    }

    fn emit(&self, opcode: &str) -> String {
        let opcodes = self
            .opcodes
            .iter()
            .map(|op| format!("{opcode}::{op}"))
            .collect::<Vec<_>>()
            .join(", ");
        let mut output = String::from("const _: () = {\n");
        for (op, count) in &self.code.formats {
            writeln!(output, "let (arity, branch) = {op}.format(); assert!(arity + if branch {{ 1 }} else {{ 0 }} == {count});").unwrap();
        }
        let types = self
            .types
            .iter()
            .map(|t| format!("&[{t}]"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(output, "}};\n#[rustfmt::skip]\nstatic PROGRAM: Program = Program {{\n    types: &[{types}],\n    names: &{:?},\n    captures: &{:?},\n    opcodes: &[{opcodes}],\n    constants: &{:?},\n    code: &[{}\n    ],\n}};",
            self.names, self.captures, self.constants, self.code.bytes.join(", ")).unwrap();
        output
    }

    fn constant(&mut self, value: u64) -> usize {
        crate::bytecode::intern(&mut self.constants, value)
    }

    fn opcode(&mut self, name: &str) -> usize {
        crate::bytecode::intern(&mut self.opcodes, name.to_owned())
    }

    fn slot(&mut self) -> usize {
        let slot = self.slots;
        self.slots += 1;
        slot
    }

    fn scan(&mut self, expr: &Expr, source: usize) -> usize {
        let Expr::Apply(op, args) = expr else {
            unreachable!("checked operation pattern")
        };
        let cursor = self.cursors;
        self.cursors += 1;
        let opcode = self.opcode(op);
        self.code.emit("Op::Open", &[cursor, source, opcode]);
        let retry = self.code.bytes.len();
        self.code.emit("Op::Next", &[cursor, self.retry]);
        let exit = self.code.bytes.len() - 4;
        self.retry = retry;
        let mut children = Vec::new();
        // Bind the entire row before opening a child cursor, which overwrites
        // the row buffer. Every first binding dominates its subsequent checks.
        for (column, arg) in args.iter().enumerate() {
            let slot = match arg {
                Expr::Variable(v) if self.bound.insert(*v) => v + 1,
                _ => self.slot(),
            };
            self.code.emit("Op::Bind", &[column, slot]);
            match arg {
                Expr::Variable(v) if slot != v + 1 => {
                    self.code.emit("Op::CheckEqual", &[v + 1, slot, retry])
                }
                Expr::Constant(value) => {
                    let constant = self.constant(*value);
                    self.code
                        .emit("Op::CheckConstant", &[slot, constant, 1, retry]);
                }
                Expr::Apply(..) => children.push((arg, slot)),
                _ => {}
            }
        }
        for (child, slot) in children {
            self.scan(child, slot);
        }
        exit
    }

    fn build(&mut self, expr: &Expr, captures: &[usize], values: &mut usize) -> usize {
        match expr {
            Expr::Variable(v) => return captures.binary_search(v).expect("captured RHS variable"),
            Expr::Constant(value) => {
                let constant = self.constant(*value);
                self.code.emit("Op::Constant", &[*values, constant]);
            }
            Expr::Apply(op, args) => {
                let args: Vec<_> = args
                    .iter()
                    .map(|arg| self.build(arg, captures, values))
                    .collect();
                let opcode = self.opcode(op);
                self.code.emit("Op::Build", &[*values, opcode, args.len()]);
                for arg in args {
                    self.code.word(arg);
                }
            }
        }
        let slot = *values;
        *values += 1;
        slot
    }
}

impl Expr {
    /// A change at any pattern position can affect the root. Store the reverse
    /// opcode path so scheduling walks only users occurring in some pattern.
    fn dependencies(
        &self,
        root: &str,
        ancestors: &mut Vec<String>,
        out: &mut BTreeSet<(String, Vec<String>)>,
    ) {
        out.insert((root.to_owned(), ancestors.iter().rev().cloned().collect()));
        if let Self::Apply(op, args) = self {
            ancestors.push(op.clone());
            for arg in args {
                arg.dependencies(root, ancestors, out);
            }
            ancestors.pop();
        }
    }
}
